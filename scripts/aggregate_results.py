"""Tables, hypothesis verdicts and figures from evaluation cells (every report number).

Usage::

    PYTHONPATH=src:. .venv/bin/python scripts/aggregate_results.py runs/evals/final \
        --thresholds docs/results/thresholds.json --out docs/results/final

Writes ``verdicts.json``, ``tables.md``, ``tables.tex`` and PNG figures to ``--out``.
"""

from __future__ import annotations

import argparse
import json
from collections import defaultdict
from pathlib import Path

import numpy as np
import yaml

from dynabelief.evaluation.aggregate import evaluate_hypothesis, load_cells

# Fixed arm order and colours (validated default categorical palette, slots 1-5).
ARMS = {
    "tarmac_pos": ("ctrl: TarMAC + position", "#2a78d6", "o"),
    "point_diabl": ("A: point DIABL", "#eb6834", "s"),
    "d_diabl_coef10": ("D: map, true occupancy", "#1baf7a", "^"),
    "d_diabl_posterior": ("C′: map, team posterior", "#eda100", "D"),
    "point_diabl_stopgrad": ("F: A + stop-gradient", "#e87ba4", "v"),
    "point_diabl_noreplay": ("E: A without replay", "#008300", "P"),
    "point_diabl_robust": ("AR: A, randomized-channel training", "#6250d6", "X"),
}
LOSSES = ["iid-p0", "iid-p0.2", "iid-p0.5", "iid-p0.8", "iid-p1"]
INK, MUTED, GRID = "#1f1f1e", "#6b6a64", "#e4e3dd"


def name(arm: str) -> str:
    return ARMS.get(arm, (arm,))[0]


def seed_means(cells, arm: str, cond: str) -> dict[int, float]:
    return {s: c["summary"]["mean_capture_rate"] for (a, s, k), c in cells.items()
            if a == arm and k == cond}  # fmt: skip


def capture_table(cells, conditions: list[str]) -> list[dict]:
    rows = []
    arms = [a for a in ARMS if any(k[0] == a for k in cells)]
    arms += sorted({k[0] for k in cells} - set(arms))
    for arm in arms:
        row = {"arm": arm}
        for cond in conditions:
            per_seed = seed_means(cells, arm, cond)
            if per_seed:
                row[cond] = (float(np.mean(list(per_seed.values()))), sorted(per_seed), per_seed)
        rows.append(row)
    return rows


def fmt_cell(entry) -> str:
    if entry is None:
        return "–"
    mean, seeds, per_seed = entry
    spread = (max(per_seed.values()) - min(per_seed.values())) / 2 if len(seeds) > 1 else None
    return f"{mean:.3f}" + (f" ± {spread:.3f}" if spread is not None else "") + f" (n={len(seeds)})"


def write_tables(out: Path, rows, conditions, verdicts) -> None:
    md = ["# Final results", "", "Capture rate on the test stream: mean over training seeds "
          "± half the seed range (n = seeds).", ""]  # fmt: skip
    md += ["| Arm | " + " | ".join(conditions) + " |", "|---" * (len(conditions) + 1) + "|"]
    for row in rows:
        md.append(f"| {name(row['arm'])} | "
                  + " | ".join(fmt_cell(row.get(c)) for c in conditions) + " |")  # fmt: skip
    md += ["", "## Hypotheses", "", "| ID | Comparison | Seeds | Estimate | 95 % CI | Verdict |",
           "|---|---|---|---|---|---|"]  # fmt: skip
    tex_v = []
    for v in verdicts:
        est = "–" if v["estimate"] is None else f"{v['estimate']:.3f}"
        ci = "–" if v["ci"] is None else f"[{v['ci'][0]:.3f}, {v['ci'][1]:.3f}]"
        comp = v.get("x", "") + (f" vs {v['y']}" if v.get("y") else "")
        label = v["id"] + (" (secondary)" if v["secondary"] else "")
        md.append(f"| {label} | {comp} | {v['seeds']} | {est} | {ci} | {v['verdict']} |")
        tex_v.append(f"{label} & {', '.join(map(str, v['seeds'])) or '--'} & {est} & {ci} & "
                     f"{v['verdict']} \\\\")  # fmt: skip
    (out / "tables.md").write_text("\n".join(md) + "\n")
    tex = ["% generated by scripts/aggregate_results.py; do not edit",
           "\\begin{tabular}{l" + "c" * len(conditions) + "}", "\\toprule",
           "Arm & " + " & ".join(c.replace("iid-p", "loss ") for c in conditions)
           + " \\\\", "\\midrule"]  # fmt: skip
    for row in rows:
        cells = []
        for c in conditions:
            e = row.get(c)
            cells.append("--" if e is None else f"{e[0]:.3f}")
        tex.append(name(row["arm"]).replace("′", "$'$") + " & " + " & ".join(cells) + " \\\\")
    tex += ["\\bottomrule", "\\end{tabular}", "", "\\begin{tabular}{lllll}", "\\toprule",
            "Hypothesis & Seeds & Estimate & 95\\,\\% CI & Verdict \\\\", "\\midrule", *tex_v,
            "\\bottomrule", "\\end{tabular}"]  # fmt: skip
    (out / "tables.tex").write_text("\n".join(tex) + "\n")


def _style(ax) -> None:
    ax.spines[["top", "right"]].set_visible(False)
    ax.spines[["left", "bottom"]].set_color(MUTED)
    ax.tick_params(colors=MUTED, labelcolor=INK)
    ax.grid(axis="y", color=GRID, linewidth=0.8)
    ax.set_axisbelow(True)


def fig_capture_vs_loss(out: Path, cells) -> None:
    import matplotlib.pyplot as plt

    xs = [float(c.split("-p")[1]) * 100 for c in LOSSES]
    fig, ax = plt.subplots(figsize=(6.4, 4.0), dpi=200)
    for arm, (label, color, marker) in ARMS.items():
        per = [seed_means(cells, arm, c) for c in LOSSES]
        if not any(per):
            continue
        mean = [np.mean(list(p.values())) if p else np.nan for p in per]
        lo = [min(p.values()) if p else np.nan for p in per]
        hi = [max(p.values()) if p else np.nan for p in per]
        n = max(len(p) for p in per)
        ax.fill_between(xs, lo, hi, color=color, alpha=0.12, linewidth=0)
        ax.plot(xs, mean, color=color, linewidth=2, marker=marker, markersize=6,
                markeredgecolor="white", markeredgewidth=1, label=f"{label} (n={n})")  # fmt: skip
    ax.set_xlabel("i.i.d. message loss (%)", color=INK)
    ax.set_ylabel("capture rate (test stream)", color=INK)
    ax.set_ylim(0, 1.02)
    ax.set_xticks(xs)
    _style(ax)
    ax.legend(frameon=False, fontsize=8, loc="lower left")
    fig.tight_layout()
    fig.savefig(out / "capture_vs_loss.png")
    plt.close(fig)


def fig_channel(out: Path, cells, thresholds: dict | None, arm: str = "point_diabl") -> None:
    import matplotlib.pyplot as plt

    labels = ["iid-p0", "iid-p0.8", "ge-p0.8-b5", "ge-p0.8-b20", "ge-p0.8-b50", "iid-p0.2",
              "iid-p0.2-n6", "iid-p0.2-n10"]  # fmt: skip
    if thresholds:
        labels += [thresholds["random"], thresholds["periodic"], thresholds["trigger"]]
    rows = [(c, seed_means(cells, arm, c)) for c in labels]
    rows = [(c, p) for c, p in rows if p]
    if not rows:
        return
    fig, ax = plt.subplots(figsize=(6.4, 0.42 * len(rows) + 1.0), dpi=200)
    ys = np.arange(len(rows))[::-1]
    color = ARMS[arm][1]
    for y, (_c, p) in zip(ys, rows, strict=True):
        m = float(np.mean(list(p.values())))
        ax.barh(y, m, height=0.6, color=color, edgecolor="white", linewidth=2)
        ax.scatter(list(p.values()), [y] * len(p), s=12, color=INK, zorder=3)
        ax.text(m + 0.01, y, f"{m:.3f}", va="center", fontsize=8, color=INK)
    ax.set_yticks(ys, [c for c, _ in rows], fontsize=8)
    ax.set_xlim(0, 1.1)
    ax.set_xlabel(f"capture rate of {name(arm)} (bars: seed mean; dots: seeds)", color=INK)
    _style(ax)
    ax.grid(axis="y", visible=False)
    ax.grid(axis="x", color=GRID, linewidth=0.8)
    fig.tight_layout()
    fig.savefig(out / "channel_conditions_A.png")
    plt.close(fig)


def fig_map_bce(out: Path, cells) -> None:
    import matplotlib.pyplot as plt

    groups = []
    for arm in ("d_diabl_coef10", "d_diabl_posterior"):
        vals = defaultdict(list)
        for (a, _s, c), cell in cells.items():
            if a == arm and c == "iid-p0":
                for key in ("model", "prior", "own_view", "filter"):
                    k = f"map_bce_remote_{key}" if key != "own_view" else "map_bce_own_view"
                    if k in cell["summary"]:
                        vals[key].append(cell["summary"][k])
        if vals:
            groups.append((arm, {k: float(np.mean(v)) for k, v in vals.items()}))
    if not groups:
        return
    fig, ax = plt.subplots(figsize=(6.4, 3.4), dpi=200)
    refs = [("prior", "prior (base rate)", "#b4b2a9"), ("filter", "team posterior (teacher)",
                                                         "#6b6a64")]  # fmt: skip
    width = 0.25
    for i, (arm, v) in enumerate(groups):
        ax.bar(i - width, v["model"], width - 0.02, color=ARMS[arm][1], label=f"{name(arm)}")
        for j, (key, lab, col) in enumerate(refs):
            if key in v:
                ax.bar(
                    i + j * width, v[key], width - 0.02, color=col, label=lab if i == 0 else None
                )
    ax.set_xticks(range(len(groups)), [name(a) for a, _ in groups], fontsize=8)
    ax.set_ylabel("remote-cell BCE (nats/cell)", color=INK)
    ax.set_title("Lower is better; cells outside the agent's own view", fontsize=9, loc="left",
                 color=MUTED)  # fmt: skip
    _style(ax)
    ax.legend(frameon=False, fontsize=8, loc="upper center", bbox_to_anchor=(0.5, -0.12), ncol=3)
    fig.tight_layout()
    fig.savefig(out / "map_remote_bce.png")
    plt.close(fig)


def main(argv: list[str] | None = None) -> int:
    p = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    p.add_argument("roots", nargs="+", type=Path)
    p.add_argument("--hypotheses", type=Path, default=Path("configs/analysis/hypotheses.yaml"))
    p.add_argument("--thresholds", type=Path)
    p.add_argument("--out", type=Path, default=Path("docs/results/final"))
    args = p.parse_args(argv)

    cells = {}
    for root in args.roots:
        cells.update(load_cells(root))
    thresholds = json.loads(args.thresholds.read_text()) if args.thresholds else None
    spec = yaml.safe_load(args.hypotheses.read_text())
    hyps = spec["hypotheses"] + spec.get("amendment_1", [])  # follow-up arms, declared later
    verdicts = [evaluate_hypothesis(h, cells, thresholds) for h in hyps]
    args.out.mkdir(parents=True, exist_ok=True)
    (args.out / "verdicts.json").write_text(json.dumps(verdicts, indent=1, default=str))
    rows = capture_table(cells, LOSSES)
    write_tables(args.out, rows, LOSSES, verdicts)
    fig_capture_vs_loss(args.out, cells)
    fig_channel(args.out, cells, thresholds)
    fig_map_bce(args.out, cells)
    for v in verdicts:
        print(f"{v['id']:6s} {v['verdict']:15s} seeds={v['seeds']} est={v['estimate']}")
    print(f"wrote {args.out}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
