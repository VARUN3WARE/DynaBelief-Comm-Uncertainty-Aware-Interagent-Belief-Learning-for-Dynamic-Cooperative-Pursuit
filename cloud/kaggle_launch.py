"""Launch and track DynaBelief-Comm jobs on Kaggle from this machine (Kaggle CLI).

Every job is a private script kernel whose code is ONE pushed commit: the generated
kernel clones the GitHub repo at that hash, so each result maps to an exact commit
(the Kaggle analogue of D12). Each person launches from their own Kaggle account;
never share API tokens (Kaggle terms). Requires ``pip install -e ".[kaggle]"`` and a
logged-in CLI (``kaggle auth login``). Job records go to ``runs/kaggle/registry.jsonl``.

Examples:
    python cloud/kaggle_launch.py bench                       # ~15 updates at 2 and 4 workers
    python cloud/kaggle_launch.py tests                       # full suite, CPU session
    python cloud/kaggle_launch.py train --config configs/point_diabl.yaml --seed 1
    python cloud/kaggle_launch.py status                      # all jobs of this account
    python cloud/kaggle_launch.py download point_diabl-s1-1103-0930
"""

from __future__ import annotations

import argparse
import json
import re
import subprocess
import sys
from datetime import datetime
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
ROOT = REPO / "runs" / "kaggle"
REGISTRY = ROOT / "registry.jsonl"
ENTRY = "cloud/kaggle_entry.py"
GPU_SHAPE = "NvidiaTeslaT4"
PREFIX = "dynabelief"
MAX_TITLE = 50

RUN_PY = """\
# Generated by cloud/kaggle_launch.py for job {name!r}. Do not edit by hand.
import os
import subprocess
import sys

REPO = {repo!r}
COMMIT = {commit!r}
ARGS = {args!r}
CODE = "/tmp/dynabelief"

subprocess.run(["git", "clone", "--quiet", REPO, CODE], check=True)
subprocess.run(["git", "-C", CODE, "checkout", "--quiet", COMMIT], check=True)
os.chdir(CODE)
sys.exit(subprocess.run([sys.executable, {entry!r}, *ARGS]).returncode)
"""


# --------------------------------------------------------------------- pure helpers
def job_name(label: str, now: datetime) -> str:
    slug = re.sub(r"[^a-z0-9-]+", "-", label.lower()).strip("-")
    stamp = f"{now:%m%d-%H%M}"
    room = MAX_TITLE - len(PREFIX) - len(stamp) - 2
    return f"{slug[:room].rstrip('-')}-{stamp}"


def kernel_title(name: str) -> str:
    """Kaggle derives the kernel slug from the title; keep them identical."""
    return f"{PREFIX}-{name}"


def kernel_metadata(user: str, name: str, gpu: bool) -> dict:
    title = kernel_title(name)
    meta = {
        "id": f"{user}/{title}",
        "title": title,
        "code_file": "run.py",
        "language": "python",
        "kernel_type": "script",
        "is_private": True,
        "enable_gpu": gpu,
        "enable_tpu": False,
        "enable_internet": True,  # git clone + pip install; the CLI's default is not reliable
        "dataset_sources": [],
        "competition_sources": [],
        "kernel_sources": [],
        "model_sources": [],
    }
    if gpu:
        meta["machine_shape"] = GPU_SHAPE
    return meta


def run_py(name: str, repo: str, commit: str, args: list[str]) -> str:
    return RUN_PY.format(name=name, repo=repo, commit=commit, args=args, entry=ENTRY)


def https_url(remote: str) -> str:
    """The kernel clones anonymously, so SSH remotes become their public HTTPS form."""
    match = re.match(r"git@github\.com:(.+)", remote)
    return f"https://github.com/{match.group(1)}" if match else remote


# --------------------------------------------------------------------- git / kaggle
def git(*args: str) -> str:
    return subprocess.run(["git", *args], cwd=REPO, check=True, capture_output=True,
                          text=True).stdout.strip()  # fmt: skip


def pushed_commit() -> str:
    """HEAD, which must be clean and already on GitHub (the kernel clones it)."""
    if git("status", "--porcelain", "--untracked-files=no"):
        raise SystemExit("working tree has uncommitted changes: commit and push first")
    commit = git("rev-parse", "HEAD")
    git("fetch", "--quiet", "origin")
    if not git("branch", "-r", "--contains", commit):
        raise SystemExit(f"{commit[:8]} is not on origin: push first (the kernel clones it)")
    return commit


def kaggle(*args: str, check: bool = True) -> str:
    exe = Path(sys.executable).with_name("kaggle")
    proc = subprocess.run([str(exe) if exe.exists() else "kaggle", *args], cwd=REPO,
                          capture_output=True, text=True)  # fmt: skip
    if check and proc.returncode != 0:
        raise SystemExit(f"kaggle {' '.join(args)} failed:\n{proc.stdout}{proc.stderr}")
    return proc.stdout + proc.stderr


def kaggle_user() -> str:
    match = re.search(r"username:\s*(\S+)", kaggle("config", "view"))
    if not match or match.group(1) == "None":
        raise SystemExit("no Kaggle username configured: run `kaggle auth login`")
    return match.group(1)


def registry() -> list[dict]:
    if not REGISTRY.exists():
        return []
    return [json.loads(line) for line in REGISTRY.read_text().splitlines() if line.strip()]


def find_job(name: str) -> dict:
    matches = [job for job in registry() if job["name"] == name]
    if not matches:
        raise SystemExit(f"unknown job {name!r}: see `kaggle_launch.py list`")
    return matches[-1]


# --------------------------------------------------------------------- commands
def launch(label: str, entry_args: list[str], gpu: bool, dry_run: bool, extra: dict) -> int:
    commit = pushed_commit()
    user = "dry-run-user" if dry_run else kaggle_user()
    name = job_name(label, datetime.now())
    kernel_dir = ROOT / name / "kernel"
    kernel_dir.mkdir(parents=True, exist_ok=True)
    meta = kernel_metadata(user, name, gpu)
    (kernel_dir / "kernel-metadata.json").write_text(json.dumps(meta, indent=1))
    remote = https_url(git("remote", "get-url", "origin"))
    (kernel_dir / "run.py").write_text(run_py(name, remote, commit, entry_args))
    print(f"job {name}\n  kernel {meta['id']}\n  commit {commit}\n  gpu    {gpu}")
    if dry_run:
        print(f"  dry run: kernel written to {kernel_dir}")
        return 0
    push = ["kernels", "push", "-p", str(kernel_dir)]
    if gpu:
        push += ["--accelerator", GPU_SHAPE]
    print(kaggle(*push).strip())
    record = {"name": name, "kernel": meta["id"], "user": user, "commit": commit, "gpu": gpu,
              "args": entry_args, "launched": datetime.now().isoformat(timespec="seconds"),
              **extra}  # fmt: skip
    REGISTRY.parent.mkdir(parents=True, exist_ok=True)
    with REGISTRY.open("a") as fh:
        fh.write(json.dumps(record) + "\n")
    return 0


def cmd_train(args: argparse.Namespace) -> int:
    overrides = [f"experiment.seed={args.seed}",
                 f"train.snapshot_every_updates={args.snapshot_every}", *args.set]  # fmt: skip
    entry = ["--mode", "train", "--config", args.config, "--workers", str(args.workers),
             "--time_limit_hours", str(args.time_limit_hours)]  # fmt: skip
    for override in overrides:
        entry += ["--set", override]
    label = args.name or f"{Path(args.config).stem}-s{args.seed}"
    extra = {"mode": "train", "config": args.config, "seed": args.seed, "overrides": overrides}
    return launch(label, entry, gpu=True, dry_run=args.dry_run, extra=extra)


def cmd_bench(args: argparse.Namespace) -> int:
    entry = ["--mode", "bench", "--config", args.config, "--bench_workers", args.workers,
             "--bench_updates", str(args.updates)]  # fmt: skip
    extra = {"mode": "bench", "config": args.config}
    return launch("bench", entry, gpu=True, dry_run=args.dry_run, extra=extra)


def cmd_tests(args: argparse.Namespace) -> int:
    entry = ["--mode", "tests", "--time_limit_hours", "2"]
    return launch("tests", entry, gpu=False, dry_run=args.dry_run, extra={"mode": "tests"})


def cmd_list(args: argparse.Namespace) -> int:
    for job in registry():
        print(f"{job['name']:40s} {job.get('mode', ''):6s} {job['commit'][:8]} {job['launched']}")
    return 0


def cmd_status(args: argparse.Namespace) -> int:
    user = kaggle_user()
    jobs = [find_job(n) for n in args.names] or [j for j in registry() if j["user"] == user]
    for job in jobs:
        state = kaggle("kernels", "status", job["kernel"], check=False).strip().splitlines()
        print(f"{job['name']:40s} {state[-1] if state else '?'}")
    return 0


def cmd_download(args: argparse.Namespace) -> int:
    job = find_job(args.name)
    out = ROOT / job["name"] / "output"
    out.mkdir(parents=True, exist_ok=True)
    print(kaggle("kernels", "output", job["kernel"], "-p", str(out), "-o").strip()[-2000:])
    for name in ("status.json", "environment.json", "bench.json"):
        path = next(iter(sorted(out.rglob(name))), None)
        if path:
            print(f"--- {path.relative_to(out)}\n{path.read_text()}")
    return 0


def build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    sub = parser.add_subparsers(dest="cmd", required=True)

    p = sub.add_parser("train", help="one training run on a T4 session")
    p.add_argument("--config", required=True)
    p.add_argument("--seed", type=int, required=True)
    p.add_argument("--set", action="append", default=[], metavar="SECTION.KEY=VALUE")
    p.add_argument("--workers", type=int, default=4, help="env workers (results do not change, D9)")
    p.add_argument("--time_limit_hours", type=float, default=11.25)
    p.add_argument("--snapshot_every", type=int, default=100, help="snapshot every N updates")
    p.add_argument("--name", help="job label (default: <config>-s<seed>)")
    p.add_argument("--dry-run", action="store_true", help="write the kernel, do not push")
    p.set_defaults(func=cmd_train)

    p = sub.add_parser("bench", help="time PPO updates per worker count")
    p.add_argument("--config", default="configs/point_diabl.yaml")
    p.add_argument("--workers", default="2,4")
    p.add_argument("--updates", type=int, default=15)
    p.add_argument("--dry-run", action="store_true")
    p.set_defaults(func=cmd_bench)

    p = sub.add_parser("tests", help="full test suite on a CPU session")
    p.add_argument("--dry-run", action="store_true")
    p.set_defaults(func=cmd_tests)

    sub.add_parser("list", help="jobs in the local registry").set_defaults(func=cmd_list)

    p = sub.add_parser("status", help="Kaggle state of registered jobs")
    p.add_argument("names", nargs="*")
    p.set_defaults(func=cmd_status)

    p = sub.add_parser("download", help="fetch a job's outputs to runs/kaggle/<job>/output")
    p.add_argument("name")
    p.set_defaults(func=cmd_download)
    return parser


def main(argv: list[str] | None = None) -> int:
    args = build_parser().parse_args(argv)
    return args.func(args)


if __name__ == "__main__":
    sys.exit(main())
